"""Create the untracked backend .env for a local/showcase deployment."""

from __future__ import annotations

import argparse
import getpass
import secrets
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'fablab-face-attendance' / '.env'


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--admin-email', default='admin@srmist.edu.in')
    parser.add_argument('--force', action='store_true', help='replace an existing .env')
    args = parser.parse_args()

    if TARGET.exists() and not args.force:
        parser.error(f'{TARGET} already exists; use --force only if replacement is intended')
    import re
    if not re.fullmatch(r'[a-z0-9._%+-]+@srmist\.edu\.in', args.admin_email.strip(), re.IGNORECASE):
        parser.error('--admin-email must use the @srmist.edu.in domain')

    password = getpass.getpass('Choose the Fab Lab administrator password: ').strip()
    if len(password) < 12:
        parser.error('administrator password must be at least 12 characters')
    access_password = getpass.getpass('Enter the shared AAMS login password: ').strip()
    if len(access_password) < 12:
        parser.error('shared AAMS login password must be at least 12 characters')

    if secrets.compare_digest(password, access_password):
        parser.error('administrator and shared credentials must be different')

    def env_value(value):
        if '\n' in value or '\r' in value:
            parser.error('environment values cannot contain newlines')
        return "'" + value.replace("'", "\\'") + "'"

    lines = [
        '# Generated by deploy/configure_showcase.py; never commit this file.',
        f'ADMIN_EMAIL={args.admin_email.strip().lower()}',
        f'API_ADMIN_PASSWORD={env_value(password)}',
        f'AAMS_ACCESS_PASSWORD={env_value(access_password)}',
        f'QR_SECRET_KEY={secrets.token_urlsafe(48)}',
        f'SESSION_SECRET_KEY={secrets.token_urlsafe(48)}',
        'SESSION_TTL_SECONDS=28800',
        'AAMS_ENV=production',
        'DATABASE_PATH=database/fablab.db',
        'TELEGRAM_BOT_TOKEN=',
        'TELEGRAM_CHAT_ID=',
        '',
    ]
    TARGET.touch(mode=0o600, exist_ok=True)
    TARGET.chmod(0o600)
    TARGET.write_text('\n'.join(lines), encoding='utf-8')
    print(f'Created {TARGET}')
    print('Start the private stack, then configure Telegram in Communicate:')
    print('  docker compose up --build -d')
    print('Public access requires a separately approved deployment.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
